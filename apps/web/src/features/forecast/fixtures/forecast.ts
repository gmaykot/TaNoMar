import type {
  FishingClassification,
  FishingForecast,
  FishingMetric,
  ForecastRankingItem,
} from '@/features/fishing/types/fishing';
import { locationsFixture } from '@/features/locations/fixtures/locations';

interface ForecastSeed {
  id: string;
  score: number;
  classification: FishingClassification;
  window: string;
  wind: string;
  wave: string;
  rain: string;
}

function metrics(seed: ForecastSeed, index: number): FishingMetric[] {
  return [
    { key: 'wind', label: 'Vento', value: seed.wind, detail: index % 2 ? 'Nordeste' : 'Leste' },
    { key: 'gusts', label: 'Rajadas', value: `${14 + index * 2} km/h` },
    { key: 'waves', label: 'Ondas', value: seed.wave },
    { key: 'wave-period', label: 'Período', value: `${7 + (index % 4)} s` },
    { key: 'swell', label: 'Swell', value: `${(0.5 + (index % 4) * 0.1).toFixed(1)} m` },
    { key: 'rain', label: 'Chuva', value: seed.rain },
    { key: 'air-temperature', label: 'Temperatura', value: `${22 + (index % 3)} °C`, detail: 'Ar' },
    { key: 'water-temperature', label: 'Água', value: `${20 + (index % 2)} °C` },
  ];
}

function ranking(seeds: ForecastSeed[]): ForecastRankingItem[] {
  return seeds.map((seed, index) => {
    const location = locationsFixture.find((item) => item.id === seed.id);
    if (!location) throw new Error(`Local de fixture desconhecido: ${seed.id}`);
    const start = seed.window.slice(0, 5);
    return {
      locationId: location.id,
      locationName: location.name,
      score: seed.score,
      classification: seed.classification,
      bestWindow: seed.window,
      bestHours: [start, '07:00', '17:00'],
      metrics: metrics(seed, index),
    };
  });
}

